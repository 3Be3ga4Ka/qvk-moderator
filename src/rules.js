// Conservative topical routing: unclear messages are allowed, never sanctioned.
export const LABELS={bugs:"🐛 Баги",ideas:"💡 Предложения",badges:"🏅 Значки",chat:"💬 Общение",releases:"📦 Бета-релизы"};
export const GUIDES={
 bugs:"Сообщай об ошибках QVK: что произошло, версию (если знаешь), как повторить и что ожидалось. Скриншоты приветствуются, но не обязательны. Уточняющие вопросы, ответы и обсуждение багов разрешены.",
 ideas:"Предлагай функции и улучшения QVK, объясняй пользу и желаемое поведение. Вопросы, обсуждение идей и уточнения разрешены. Упоминание бага как причины улучшения — не нарушение.",
 badges:"Здесь подают заявки на значок тестировщика QVK: можно указать VK ID или ссылку на профиль. Вопросы о заявке, статусе, условиях и выдаче значков тоже разрешены. Не отправляй пароли и токены.",
 chat:"Свободное общение о QVK, помощи и сообществе. Уважай участников; флуд и опасные ссылки проверяет отдельный антиспам.",
 releases:"Здесь команда публикует сборки QVK и изменения. Обсуждение, вопросы и благодарности пользователей допустимы; только публикацию официальных релизов следует ограничивать полномочиями команды."
};
const bug=/\b(?:bug|crash)\b|(?:баг|ошибк|вылет|вылета|краш|завис|сломал|перестал(?:о|а)? работать|не работает|не открыва|не загружа|не приход|не показывает)/iu;
const idea=/(?:предлагаю|предложение|идея|хотелось бы|было бы удобн|добав(?:ить|ьте)|сделайте|реализовать|новую функцию|функционал)/iu;
const clearIdea=/(?:^|\n|[.!?]\s+)(?:я\s+)?(?:предлагаю|предложение[:\s]|идея[:\s]|хотелось бы|добавьте|сделайте|нужно добавить|можно добавить|было бы удобно)/iu;
const clearBug=/(?:приложение|qvk|клиент|видео|авторизац|уведомлени|плеер|чат|сообщени|музык|лента|при открытии|при запуске|после обновления).{0,100}(?:вылета|краш|не работает|не открыва|завис|ошибк)|(?:вылета|краш|не работает|не открыва|завис|ошибк).{0,100}(?:приложение|qvk|клиент|видео|авторизац|уведомлени|плеер|чат|сообщени|музык|лента)/iu;
const badge=/(?:знач(?:ок|ка|ки|ков)|тестер|выда(?:ть|ча|ли)|заявк|профил|vk\.com|вк\s*id)/iu;
const questions=/[?？]|\b(?:как|почему|можно|подскажите|скажите|кто|когда|где|зачем)\b/iu;
const response=/^(?:да|нет|спасибо|ок|ага|понятно|проверю|согласен|не согласен|попробуй|у меня|аналогично|тоже|вот|это|ну)\b/iu;
const quotes=/(?:^|\n)\s*(?:>|«|цитат)/iu;
export function assess(kind,content="",hasMedia=false){
 const text=String(content||"").trim();
 const uncertain=reason=>({verdict:"uncertain",reason});
 if(kind==="chat")return {verdict:"ok",reason:"Свободное общение"};
 if(kind==="releases")return uncertain("Проверка релизов требует контекста и роли отправителя");
 if(!text)return uncertain(hasMedia?"Медиа без подписи":"Нет текста");
 // Short replies, quoted material, questions and mixed topics must not trigger sanctions.
 if(text.length<34||questions.test(text)||response.test(text)||quotes.test(text))return uncertain("Недостаточно контекста для уверенного определения темы");
 const b=bug.test(text),i=idea.test(text),v=badge.test(text);
 if(kind==="bugs"){
  if(b)return {verdict:"ok",reason:"Обсуждение неисправности"};
  if(i&&clearIdea.test(text)&&!v&&text.length>=48)return {verdict:"offtopic",reason:"Самостоятельное предложение новой функции без описания ошибки QVK"};
 }
 if(kind==="ideas"){
  if(i)return {verdict:"ok",reason:"Обсуждение улучшения"};
  if(b&&clearBug.test(text)&&!v&&text.length>=48)return {verdict:"offtopic",reason:"Подробное описание ошибки вместо предложения"};
 }
 if(kind==="badges"){
  if(v)return {verdict:"ok",reason:"Обсуждение значков и заявок"};
  // Badge topic is particularly sensitive: request clarification instead of assigning blame.
 }
 return uncertain("Нет однозначных признаков нарушения: сообщение допускается");
}
